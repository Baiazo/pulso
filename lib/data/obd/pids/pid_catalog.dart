double _singleByteIdentity(List<int> b) => b[0].toDouble();

double _engineLoad(List<int> b) => b[0] * 100 / 255;

double _coolantTemp(List<int> b) => (b[0] - 40).toDouble();

double _fuelTrim(List<int> b) => (b[0] - 128) * 100 / 128;

double _fuelPressure(List<int> b) => (b[0] * 3).toDouble();

double _engineRpm(List<int> b) => (256 * b[0] + b[1]) / 4;

double _timingAdvance(List<int> b) => b[0] / 2 - 64;

double _mafRate(List<int> b) => (256 * b[0] + b[1]) / 100;

double _twoByteBigEndian(List<int> b) => (256 * b[0] + b[1]).toDouble();

double _catalystTemp(List<int> b) => (256 * b[0] + b[1]) / 10 - 40;

double _controlModuleVoltage(List<int> b) => (256 * b[0] + b[1]) / 1000;

double _absoluteLoad(List<int> b) => (256 * b[0] + b[1]) * 100 / 255;

double _commandedEquivRatio(List<int> b) => (256 * b[0] + b[1]) / 32768;

double _fuelRate(List<int> b) => (256 * b[0] + b[1]) / 20;
